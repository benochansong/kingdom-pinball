export function translateText(text: string, language: Language) {
  if (language !== "en") return text;
  const trimmed = text.trim();
  const translated = TEXT[trimmed];
  if (translated) return text.replace(trimmed, translated);
  const withKey = trimmed.match(/^([A-Z⇥]) (.+)$/);
  if (withKey && TEXT[withKey[2]]) return `${withKey[1]} ${TEXT[withKey[2]]}`;
  return text;
}
